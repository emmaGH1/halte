function spriteSVG(name, px = 10) {
  const g = SPRITES[name]; let r = "";
  g.forEach((row, y) => [...row].forEach((ch, x) => { if (ch !== ".") r += `<rect x="${x * px}" y="${y * px}" width="${px + .5}" height="${px + .5}" fill="${PAL[ch]}"/>`; }));
  return `<svg viewBox="0 0 ${16 * px} ${16 * px}" width="${16 * px}" height="${16 * px}" shape-rendering="crispEdges" aria-hidden="true">${r}</svg>`;
}
